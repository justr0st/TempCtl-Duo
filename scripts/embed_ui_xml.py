"""Embed the LVGL Pro project (ui/) into the firmware.

Collects ui/globals.xml, ui/components/**/*.xml and ui/screens/**/*.xml and
writes them as C strings to src/ui_xml_data.h. The firmware registers them
with LVGL's XML loader at start-up (see uiLoadXml() in src/ui.cpp).

Runs automatically before every PlatformIO build (extra_scripts in
platformio.ini). Can also be run by hand:  python scripts/embed_ui_xml.py
"""
import os
import sys

HEADER = "src/ui_xml_data.h"


def collect(root):
    files = []
    g = os.path.join(root, "globals.xml")
    if not os.path.isfile(g):
        sys.exit("embed_ui_xml: %s not found" % g)
    files.append(("globals", g, "globals"))
    for kind in ("components", "screens"):
        base = os.path.join(root, kind)
        found = []
        for dirpath, _, names in os.walk(base):
            for n in names:
                if n.lower().endswith(".xml"):
                    found.append((os.path.splitext(n)[0], os.path.join(dirpath, n), kind))
        found.sort(key=lambda f: f[0])
        seen = {}
        for name, path, k in found:
            if name in seen:
                sys.exit("embed_ui_xml: duplicate element name '%s' (%s and %s)" % (name, seen[name], path))
            seen[name] = path
        files.extend(found)
    return files


def c_string(text):
    out = []
    for line in text.replace("\r\n", "\n").split("\n"):
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        out.append('    "%s\\n"' % esc)
    return "\n".join(out)


def generate(project_dir):
    root = os.path.join(project_dir, "ui")
    files = collect(root)
    parts = [
        "// Generated by scripts/embed_ui_xml.py from the LVGL Pro project in ui/.",
        "// Do not edit: change the XML files and rebuild.",
        "#pragma once",
        "",
        "struct UiXmlFile {",
        "  const char* name;  // element name (file name without .xml)",
        "  const char* kind;  // globals / components / screens",
        "  const char* xml;",
        "};",
        "",
        "static const UiXmlFile UI_XML_FILES[] = {",
    ]
    for name, path, kind in files:
        with open(path, "r", encoding="utf-8") as f:
            text = f.read()
        parts.append('  {"%s", "%s",' % (name, kind))
        parts.append(c_string(text) + "},")
    parts.append("};")
    parts.append("static const int UI_XML_COUNT = sizeof(UI_XML_FILES) / sizeof(UI_XML_FILES[0]);")
    parts.append("")
    content = "\n".join(parts)
    out = os.path.join(project_dir, HEADER)
    old = None
    if os.path.isfile(out):
        with open(out, "r", encoding="utf-8") as f:
            old = f.read()
    if old != content:  # keep the timestamp if nothing changed (no needless rebuilds)
        with open(out, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
    print("embed_ui_xml: %d XML files -> %s" % (len(files), HEADER))


try:
    Import("env")  # noqa: F821  (PlatformIO/SCons)
    generate(env.subst("$PROJECT_DIR"))  # noqa: F821
except NameError:
    generate(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
