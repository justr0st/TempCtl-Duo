"""Writes the sheet as a KiCad 7 project: .kicad_sch (lib symbols embedded), TempCtlDuo.kicad_sym, sym-lib-table,
.kicad_pro. Everything is placed unrotated; schematic y = symbol y negated."""
import json
import os
import sys

from model import G, uid
from sheet import L
F = lambda v: f"{v * G:.4f}".rstrip("0").rstrip(".") if not float(v * G).is_integer() else str(int(v * G))
M = lambda v: f"{v:.4f}".rstrip("0").rstrip(".") if not float(v).is_integer() else str(int(v))  # value already mm


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def font(size=1.27, bold=False):
    return f"(font (size {M(size)} {M(size)}){' bold' if bold else ''})"


def sym_body(sd, name):
    """lib symbol s-expression; name = 'TempCtlDuo:R_V' (embedded) or 'R_V' (library file)"""
    short = sd.name
    o = [f"(symbol {q(name)}"]
    if sd.power:
        o.append("(power)")
    if sd.numbers_hidden:
        o.append("(pin_numbers hide)")
    o.append(f"(pin_names (offset {M(sd.name_offset)}){' hide' if sd.names_hidden else ''})")
    o.append("(in_bom yes) (on_board yes)")
    rx, ry, ra = sd.ref_at
    vx, vy, va = sd.val_at
    o.append(f"(property \"Reference\" {q(sd.prefix)} (at {M(rx)} {M(ry)} {ra}) (effects {font()}{' hide' if sd.power else ''}))")
    o.append(f"(property \"Value\" {q(sd.value)} (at {M(vx)} {M(vy)} {va}) (effects {font()}))")
    o.append(f"(property \"Footprint\" \"\" (at 0 0 0) (effects {font()} hide))")
    o.append(f"(property \"Datasheet\" \"~\" (at 0 0 0) (effects {font()} hide))")
    if sd.desc:
        o.append(f"(property \"ki_description\" {q(sd.desc)} (at 0 0 0) (effects {font()} hide))")
    g = [f"(symbol {q(short + '_0_1')}"]
    for item in sd.graphics:
        if item[0] == "rect":
            _, x1, y1, x2, y2, fill = item
            g.append(f"(rectangle (start {M(x1)} {M(y1)}) (end {M(x2)} {M(y2)}) (stroke (width 0.254) (type default)) (fill (type {fill})))")
        elif item[0] == "poly":
            _, pts, w, fill = item
            p = " ".join(f"(xy {M(x)} {M(y)})" for x, y in pts)
            g.append(f"(polyline (pts {p}) (stroke (width {M(w)}) (type default)) (fill (type {fill})))")
        elif item[0] == "circle":
            _, cx, cy, r, w, fill = item
            g.append(f"(circle (center {M(cx)} {M(cy)}) (radius {M(r)}) (stroke (width {M(w)}) (type default)) (fill (type {fill})))")
    g.append(")")
    o.append(" ".join(g))
    pins = [f"(symbol {q(short + '_1_1')}"]
    for p in sd.pins:
        hide = " hide" if (sd.power and p.name_hidden) else ""
        pins.append(f"(pin {p.typ} line (at {F(p.x)} {F(p.y)} {p.angle}) (length {F(p.length)}){hide} "
                    f"(name {q(p.name)} (effects {font()})) (number {q(p.num)} (effects {font()})))")
    pins.append(")")
    o.append(" ".join(pins))
    o.append(")")
    return " ".join(o)


def write(S, outdir):
    """the .kicad_sch and .kicad_pro of one sheet"""
    os.makedirs(outdir, exist_ok=True)
    PROJECT = S.project
    ROOT = uid("root-sheet") if PROJECT == "TempCtl-Duo-S3" else uid("root-sheet", PROJECT)
    used = []
    for p in S.parts:
        if p.sym not in used:
            used.append(p.sym)
    o = [f"(kicad_sch (version 20230121) (generator eeschema)", f"(uuid {ROOT})", '(paper "A3")',
         f"(title_block (title {q(S.ktitle)}) (date \"2026-10-13\") (rev {q(S.rev)})"
         f" (company \"TempCtl Duo\") (comment 1 {q(S.kcomment)})"
         " (comment 2 \"Generated by hardware/gen; edit freely in KiCad\"))",
         "(lib_symbols"]
    for sd in used:
        o.append(sym_body(sd, sd.lib_id))
    o.append(")")
    for x, y in S.junctions:
        o.append(f"(junction (at {F(x)} {F(y)}) (diameter 0) (color 0 0 0 0) (uuid {uid('j', x, y)}))")
    for x, y in S.ncs:
        o.append(f"(no_connect (at {F(x)} {F(y)}) (uuid {uid('nc', x, y)}))")
    for i, ((x1, y1), (x2, y2)) in enumerate(S.wires):
        o.append(f"(wire (pts (xy {F(x1)} {F(y1)}) (xy {F(x2)} {F(y2)})) (stroke (width 0) (type default)) (uuid {uid('w', i)}))")
    for i, (x1, y1, x2, y2, title) in enumerate(S.frames):
        pts = [(x1, y1), (x2, y1), (x2, y2), (x1, y2), (x1, y1)]
        for k, (a, b) in enumerate(zip(pts, pts[1:])):
            o.append(f"(polyline (pts (xy {F(a[0])} {F(a[1])}) (xy {F(b[0])} {F(b[1])})) (stroke (width 0.254) (type dash))"
                     f" (uuid {uid('fr', i, k)}))")
        o.append(f"(text {q(title)} (at {F(x1 + 1)} {F(y1 + 3)} 0) (effects {font(2.0, True)} (justify left bottom)) (uuid {uid('ft', i)}))")
    for i, (x, y, s, size, bold) in enumerate(S.texts):
        o.append(f"(text {q(s)} (at {F(x)} {F(y)} 0) (effects {font(size, bold)} (justify left bottom)) (uuid {uid('t', i)}))")
    for i, (name, x, y, ang) in enumerate(S.labels):
        j = "left" if ang == 0 else "right"
        o.append(f"(label {q(name)} (at {F(x)} {F(y)} {ang}) (fields_autoplaced) (effects {font()} (justify {j} bottom)) (uuid {uid('l', i)}))")
    for p in S.parts:
        sd = p.sym
        o.append(f"(symbol (lib_id {q(sd.lib_id)}) (at {F(p.x)} {F(p.y)} 0) (unit 1)")
        o.append(f"(in_bom {'no' if sd.power else 'yes'}) (on_board yes) (dnp {'yes' if p.dnp else 'no'})")
        o.append(f"(uuid {uid('p', p.ref)})")
        if p.ref_pos:
            rx, ry, rj = p.ref_pos
        else:
            rx, ry, rj = p.x + sd.ref_at[0] / G, p.y - sd.ref_at[1] / G, "center"
        if p.val_pos:
            vx, vy, vj = p.val_pos
        else:
            vx, vy, vj = p.x + sd.val_at[0] / G, p.y - sd.val_at[1] / G, "center"
        jr = "" if rj == "center" else f" (justify {rj})"
        jv = "" if vj == "center" else f" (justify {vj})"
        o.append(f"(property \"Reference\" {q(p.ref)} (at {F(rx)} {F(ry)} 0) (effects {font()}{jr}{' hide' if p.hide_ref else ''}))")
        o.append(f"(property \"Value\" {q(p.value)} (at {F(vx)} {F(vy)} 0) (effects {font()}{jv}))")
        o.append(f"(property \"Footprint\" \"\" (at {F(p.x)} {F(p.y)} 0) (effects {font()} hide))")
        o.append(f"(property \"Datasheet\" \"~\" (at {F(p.x)} {F(p.y)} 0) (effects {font()} hide))")
        for pin in sd.pins:
            o.append(f"(pin {q(pin.num)} (uuid {uid('pin', p.ref, pin.num)}))")
        o.append(f"(instances (project {q(PROJECT)} (path \"/{ROOT}\" (reference {q(p.ref)}) (unit 1))))")
        o.append(")")
    o.append('(sheet_instances (path "/" (page "1")))')
    o.append(")")
    open(f"{outdir}/{PROJECT}.kicad_sch", "w").write(pretty("\n".join(o)) + "\n")
    pro = {"meta": {"filename": f"{PROJECT}.kicad_pro", "version": 1},
           "sheets": [[ROOT, ""]], "text_variables": {}}
    open(f"{outdir}/{PROJECT}.kicad_pro", "w").write(json.dumps(pro, indent=2) + "\n")


def write_lib(sheets, outdir):
    """the project library: the TempCtlDuo symbols used by these sheets (for editing / reuse) + sym-lib-table"""
    used = {id(p.sym) for S in sheets for p in S.parts}
    libsyms = [sd for sd in L.values() if sd.lib == "TempCtlDuo" and id(sd) in used]
    lo = ["(kicad_symbol_lib (version 20220914) (generator kicad_symbol_editor)"]
    for sd in libsyms:
        lo.append(sym_body(sd, sd.name))
    lo.append(")")
    open(f"{outdir}/TempCtlDuo.kicad_sym", "w").write(pretty("\n".join(lo)) + "\n")
    open(f"{outdir}/sym-lib-table", "w").write(
        '(sym_lib_table\n  (lib (name "TempCtlDuo")(type "KiCad")(uri "${KIPRJMOD}/TempCtlDuo.kicad_sym")(options "")'
        '(descr "TempCtl Duo modules and parts"))\n)\n')


def pretty(s):
    """indent the s-expression one item per line at the top two levels (KiCad reads any whitespace)"""
    out, depth, i, line = [], 0, 0, []
    tokens = []
    buf, instr, esc = "", False, False
    for ch in s:
        if instr:
            buf += ch
            if esc:
                esc = False
            elif ch == "\\":
                esc = True
            elif ch == '"':
                instr = False
            continue
        if ch == '"':
            instr = True
            buf += ch
        elif ch in "()":
            if buf.strip():
                tokens.append(buf.strip())
            buf = ""
            tokens.append(ch)
        elif ch.isspace():
            if buf.strip():
                tokens.append(buf.strip())
            buf = ""
        else:
            buf += ch
    res = []
    for t in tokens:
        if t == "(":
            if depth <= 2:
                res.append("\n" + "  " * depth + "(")
            else:
                res.append(" (")
            depth += 1
        elif t == ")":
            depth -= 1
            res.append(")")
        else:
            res.append(t if res and res[-1].endswith("(") else " " + t)
    return "".join(res).strip()
