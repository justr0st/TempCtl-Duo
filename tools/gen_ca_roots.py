#!/usr/bin/env python3
"""Writes src/ca_roots.h: the root certificates the S3 trusts for the firmware download from the release page
(spec 9.13, ota_net.cpp). The release page is on GitHub Pages (justr0st.github.io: DigiCert or Sectigo
certificates; with a custom domain Let's Encrypt); the earlier Cloudflare page (workers.dev: Let's Encrypt, Google
Trust Services, SSL.com, backup Sectigo) stays covered too. The roots below cover these chains and cross-signs.
Source: the Mozilla CA list of the Python package certifi (pip install certifi).
  python3 tools/gen_ca_roots.py"""
import os, re, certifi

ROOTS = [  # subject CN in certifi's cacert.pem
    "ISRG Root X1", "ISRG Root X2",                                   # Let's Encrypt
    "GTS Root R1", "GTS Root R3", "GTS Root R4",                      # Google Trust Services
    "GlobalSign Root R46", "GlobalSign Root E46",
    "SSL.com Root Certification Authority RSA", "SSL.com Root Certification Authority ECC",
    "SSL.com TLS RSA Root CA 2022", "SSL.com TLS ECC Root CA 2022",
    "Certum Trusted Network CA",                                      # (SSL.com cross-sign)
    "USERTrust RSA Certification Authority", "USERTrust ECC Certification Authority",
    "Sectigo Public Server Authentication Root R46", "Sectigo Public Server Authentication Root E46",
    "DigiCert Global Root G2", "DigiCert Global Root G3",             # (GitHub Pages)
]

text = open(certifi.where(), encoding="utf-8").read()
blocks = re.findall(r"^# Subject: CN=(.+?)(?: O=.*)?\n(?:#.*\n)*(-----BEGIN CERTIFICATE-----\n[\s\S]+?-----END CERTIFICATE-----)", text, re.M)
by = {cn.strip(): pem for cn, pem in blocks}
missing = [r for r in ROOTS if r not in by]
if missing:
    raise SystemExit("not in certifi %s: %s" % (certifi.__version__, ", ".join(missing)))
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = os.path.join(root, "src", "ca_roots.h")
with open(out, "w", newline="\n") as f:
    f.write("// generated by tools/gen_ca_roots.py (certifi %s) - do not edit\n" % certifi.__version__)
    f.write("// root certificates for the firmware download from the release page (spec 9.13, ota_net.cpp)\n")
    f.write("#pragma once\n\nstatic const char CA_ROOTS[] =\n")
    for name in ROOTS:
        f.write("    // %s\n" % name)
        for line in by[name].splitlines():
            f.write('    "%s\\n"\n' % line)
    f.write("    ;\n")
print("gen_ca_roots: %d roots -> %s" % (len(ROOTS), os.path.relpath(out, root)))
