# Embeds the web page (web/index.html, gzipped), the Barlow fonts (web/fonts/*.woff2)
# and the icons (web/icons/, made from logo/) into src/web_assets.h, served by src/web.cpp.
#
# Runs automatically before every PlatformIO build (platformio.ini:
# extra_scripts = pre:tools/web_embed.py) and rewrites the header only when
# its content changes. Can also be run by hand: python tools/web_embed.py
import gzip
import os

try:
    Import("env")  # noqa: F821  (PlatformIO / SCons)
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
except NameError:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

WEB = os.path.join(ROOT, "web")
OUT = os.path.join(ROOT, "src", "web_assets.h")

# (url, file, content type, gzip, immutable)
ASSETS = [
    ("/", "index.html", "text/html; charset=utf-8", True, False),
    ("/f/barlow-400.woff2", "fonts/barlow-400.woff2", "font/woff2", False, True),
    ("/f/barlow-500.woff2", "fonts/barlow-500.woff2", "font/woff2", False, True),
    ("/f/barlow-600.woff2", "fonts/barlow-600.woff2", "font/woff2", False, True),
    ("/f/barlow-semi-condensed-600.woff2", "fonts/barlow-semi-condensed-600.woff2", "font/woff2", False, True),
    ("/f/OFL.txt", "fonts/OFL.txt", "text/plain; charset=utf-8", True, True),
    ("/favicon.svg", "icons/logo.svg", "image/svg+xml", True, False),
    ("/favicon.ico", "icons/favicon.ico", "image/x-icon", False, False),
    ("/apple-touch-icon.png", "icons/apple-touch-icon.png", "image/png", False, False),
    # the page without the web fonts (system fonts): boards without PSRAM (CYD) serve this one,
    # four 22 kB font downloads at once need more RAM than the CYD has left
    ("/nofonts", "index.html", "text/html; charset=utf-8", True, False),
]


def only(url):
    """the boards an asset is compiled into (the S3 serves the page with the web fonts, the CYD without them
    and no fonts: about 130 kB less in the CYD's firmware slot)"""
    if url == "/" or url.endswith(".woff2"):
        return "#ifdef BOARD_HAS_PSRAM"
    if url == "/nofonts":
        return "#ifndef BOARD_HAS_PSRAM"
    return None


def c_bytes(data):
    lines = []
    for i in range(0, len(data), 20):
        lines.append("  " + ",".join(str(b) for b in data[i:i + 20]) + ",")
    return "\n".join(lines)


def build():
    parts = [
        "// Generated by tools/web_embed.py from web/ - do not edit (rebuilt before every build).",
        "#pragma once",
        "#include <pgmspace.h>",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "struct WebAsset {",
        "  const char* path;",
        "  const char* type;",
        "  const uint8_t* data;",
        "  size_t len;",
        "  bool gzip;       // sent with Content-Encoding: gzip",
        "  bool immutable;  // long browser cache (fonts)",
        "};",
        "",
    ]
    table = []
    total = 0
    for n, (url, rel, ctype, gz, imm) in enumerate(ASSETS):
        with open(os.path.join(WEB, rel), "rb") as f:
            data = f.read()
        if rel == "index.html":  # the device's copy: the page knows it is served by a device (spec 7b)
            data = data.replace(b'<html lang="en">', b'<html lang="en" data-device>', 1)
        if url == "/nofonts":
            data = b"\n".join(l for l in data.split(b"\n") if not l.lstrip().startswith(b"@font-face"))
        if gz:
            data = gzip.compress(data, compresslevel=9, mtime=0)
        total += len(data)
        cond = only(url)
        if cond:
            parts.append(cond)
        parts.append("// %s (%d bytes%s)" % (rel, len(data), ", gzip" if gz else ""))
        parts.append("static const uint8_t WA_%d[] PROGMEM = {" % n)
        parts.append(c_bytes(data))
        parts.append("};")
        if cond:
            parts.append("#endif")
            table.append(cond)
        served = "/" if url == "/nofonts" else url  # (the CYD serves the page without fonts at /)
        table.append('  {"%s", "%s", WA_%d, %d, %s, %s},' % (served, ctype, n, len(data), str(gz).lower(), str(imm).lower()))
        if cond:
            table.append("#endif")
    parts.append("")
    parts.append("// %d bytes in all (both boards; each board compiles in only its own page / fonts)" % total)
    parts.append("static const WebAsset WEB_ASSETS[] = {")
    parts.extend(table)
    parts.append("};")
    parts.append("static const size_t WEB_ASSET_COUNT = sizeof(WEB_ASSETS) / sizeof(WEB_ASSETS[0]);")
    parts.append("")
    text = "\n".join(parts)
    old = None
    if os.path.exists(OUT):
        with open(OUT, "r") as f:
            old = f.read()
    if old != text:
        with open(OUT, "w", newline="\n") as f:
            f.write(text)
        print("web_embed: wrote %s (%d bytes of assets)" % (os.path.relpath(OUT, ROOT), total))


if not os.environ.get("WEB_EMBED_NO_BUILD"):  # (tools/build_site.py only borrows the asset list)
    build()
