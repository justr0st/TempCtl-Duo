#!/usr/bin/env python3
"""LVGL 9 bitmap font generator (lv_font_fmt_txt, 4 bpp, no compression).

A small stand-in for lv_font_conv (not reachable from every build machine):
renders the glyphs with FreeType (Pillow) and writes a C file in the same
format. Kerning pairs of the font's 'kern' / GPOS pair table are not used.

  python3 tools/lv_font_gen.py --font tools/fonts/barlow-500.ttf --size 14 \
      --range 0x20-0x7E,0xA0-0xFF,0x2013-0x2014,0x2026,0x2212 \
      --name font_b500_14 --fallback lv_font_montserrat_14 -o src/fonts/font_b500_14.c

--fallback: an LVGL font for characters this font doesn't have (e.g. the
LV_SYMBOL_* icons of LVGL's built-in Montserrat fonts).
"""
import argparse
import os
from PIL import Image, ImageDraw, ImageFont


def parse_ranges(s):
    out = []
    for part in s.split(','):
        part = part.strip()
        if not part:
            continue
        if '-' in part[2:]:
            a, b = part.split('-', 1) if not part.startswith('-') else (part, part)
            out.extend(range(int(a, 0), int(b, 0) + 1))
        else:
            out.append(int(part, 0))
    return sorted(set(out))


def render(font, ch, ascent):
    """-> (adv16, w, h, ofs_x, ofs_y, 4-bit pixels row by row)"""
    adv = font.getlength(ch)
    x0, y0, x1, y1 = font.getbbox(ch)  # from the origin at the ascender line
    w, h = max(0, x1 - x0), max(0, y1 - y0)
    ox, oy = x0, y0
    px = []
    if w and h:
        im = Image.new('L', (w, h), 0)
        ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255)
        px = list(im.tobytes())
    # trim empty borders
    rows = [px[y * w:(y + 1) * w] for y in range(h)]
    while rows and not any(rows[0]):
        rows.pop(0)
        oy += 1
    while rows and not any(rows[-1]):
        rows.pop()
    if rows:
        left = min(next(i for i, v in enumerate(r) if v) for r in rows if any(r))
        right = max(len(r) - next(i for i, v in enumerate(reversed(r)) if v) for r in rows if any(r))
        rows = [r[left:right] for r in rows]
        ox += left
    h = len(rows)
    w = len(rows[0]) if rows else 0
    bits = [min(15, (v + 8) >> 4) for r in rows for v in r]
    ofs_y = ascent - (oy + h)  # bottom of the box above the baseline
    return int(round(adv * 16)), w, h, ox, ofs_y, bits


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--font', required=True)
    ap.add_argument('--size', type=int, required=True)
    ap.add_argument('--range', required=True)
    ap.add_argument('--name', required=True)
    ap.add_argument('--fallback', default='')
    ap.add_argument('-o', '--out', required=True)
    a = ap.parse_args()

    font = ImageFont.truetype(a.font, a.size, layout_engine=ImageFont.Layout.BASIC)
    ascent, descent = font.getmetrics()
    from fontTools.ttLib import TTFont
    cmap = TTFont(a.font).getBestCmap()
    cps = [c for c in parse_ranges(a.range) if c in cmap]

    glyphs = []
    for c in cps:
        glyphs.append((c,) + render(font, chr(c), ascent))

    # bitmap: each glyph's pixels packed continuously (2 per byte), padded to a byte
    bitmap = []
    dsc = []
    for c, adv, w, h, ox, oy, bits in glyphs:
        idx = len(bitmap)
        for i in range(0, len(bits), 2):
            hi = bits[i]
            lo = bits[i + 1] if i + 1 < len(bits) else 0
            bitmap.append((hi << 4) | lo)
        dsc.append((idx, adv, w, h, ox, oy, c))

    # cmaps: one per run of consecutive code points
    runs = []
    for i, (c, *_rest) in enumerate(glyphs):
        if runs and c == runs[-1][0] + runs[-1][1]:
            runs[-1][1] += 1
        else:
            runs.append([c, 1, i + 1])

    cap = font.getbbox('H')
    xh = font.getbbox('x')
    cap_h = ascent - cap[1] if cap else 0
    x_h = ascent - xh[1] if xh else 0

    n = a.name
    L = []
    L.append(f'// {os.path.basename(a.out)}: generated by tools/lv_font_gen.py - do not edit')
    L.append(f'// {os.path.basename(a.font)}, {a.size} px, 4 bpp, ranges {a.range}')
    L.append('#include "lvgl.h"\n')
    L.append('static const uint8_t glyph_bitmap[] = {')
    for i in range(0, len(bitmap), 24):
        L.append('    ' + ', '.join(f'0x{b:02x}' for b in bitmap[i:i + 24]) + ',')
    if not bitmap:
        L.append('    0')
    L.append('};\n')
    L.append('static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {')
    L.append('    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},')
    for idx, adv, w, h, ox, oy, c in dsc:
        L.append(f'    {{.bitmap_index = {idx}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, .ofs_x = {ox}, .ofs_y = {oy}}}, /* U+{c:04X} */')
    L.append('};\n')
    L.append('static const lv_font_fmt_txt_cmap_t cmaps[] = {')
    for start, length, gid in runs:
        L.append(f'    {{.range_start = {start}, .range_length = {length}, .glyph_id_start = {gid}, .unicode_list = NULL, '
                 f'.glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY}},')
    L.append('};\n')
    L.append('static const lv_font_fmt_txt_dsc_t font_dsc = {')
    L.append('    .glyph_bitmap = glyph_bitmap,\n    .glyph_dsc = glyph_dsc,\n    .cmaps = cmaps,\n    .kern_dsc = NULL,')
    L.append(f'    .kern_scale = 0,\n    .cmap_num = {len(runs)},\n    .bpp = 4,\n    .kern_classes = 0,\n    .bitmap_format = 0,')
    L.append('};\n')
    if a.fallback:
        L.append(f'extern const lv_font_t {a.fallback};')
    L.append(f'const lv_font_t {n} = {{')
    L.append('    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,\n    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,')
    L.append(f'    .line_height = {ascent + descent},\n    .base_line = {descent},')
    L.append(f'    .cap_height = {cap_h},\n    .x_height = {x_h},')
    L.append('    .subpx = LV_FONT_SUBPX_NONE,\n    .underline_position = -1,\n    .underline_thickness = 1,')
    L.append('    .static_bitmap = 1,\n    .dsc = &font_dsc,')
    L.append(f'    .fallback = {"&" + a.fallback if a.fallback else "NULL"},')
    L.append('    .user_data = NULL,\n};')
    os.makedirs(os.path.dirname(a.out) or '.', exist_ok=True)
    with open(a.out, 'w') as f:
        f.write('\n'.join(L) + '\n')
    print(f'{a.out}: {len(glyphs)} glyphs, {len(bitmap)} bytes bitmap, line height {ascent + descent}')


if __name__ == '__main__':
    main()
